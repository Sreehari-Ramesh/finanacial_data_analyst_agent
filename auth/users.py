"""User lookup, verification, and creation against the SQLite auth DB."""
import sqlite3
import bcrypt
from auth.db import get_connection, init_db


def get_user(username: str) -> dict | None:
    init_db()
    with get_connection() as conn:
        row = conn.execute(
            "SELECT id, username, password_hash, role, is_active "
            "FROM users WHERE username = ?",
            (username,),
        ).fetchone()
    if not row:
        return None
    return {
        "id":            row["id"],
        "username":      row["username"],
        "password_hash": row["password_hash"],
        "role":          row["role"],
        "is_active":     bool(row["is_active"]),
    }


def verify_password(username: str, password: str) -> dict | None:
    """Return user dict if credentials are valid and account is active, else None."""
    user = get_user(username)
    if not user or not user["is_active"]:
        return None
    if bcrypt.checkpw(password.encode(), user["password_hash"].encode()):
        return {k: v for k, v in user.items() if k != "password_hash"}
    return None


def create_user(username: str, password: str) -> tuple[bool, str]:
    """Register a new user account. Returns (success, error_message).

    Role defaults to 'user'. Admin accounts are created via scripts/create_user.py only.
    ID is auto-generated by SQLite — no external IDs required.
    """
    init_db()
    if not username or len(username.strip()) < 3:
        return False, "Username must be at least 3 characters."
    if len(password) < 6:
        return False, "Password must be at least 6 characters."

    password_hash = bcrypt.hashpw(password.encode(), bcrypt.gensalt()).decode()
    try:
        with get_connection() as conn:
            conn.execute(
                "INSERT INTO users (username, password_hash, role) VALUES (?, ?, 'user')",
                (username.strip(), password_hash),
            )
            conn.commit()
        return True, ""
    except sqlite3.IntegrityError:
        return False, "Username already taken. Please choose a different one."
